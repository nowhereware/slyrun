#!/usr/bin/env python3
"""Cuts the website's world art out of the page into standalone SVGs for Godot.

The hills' trees and the ground's rocks, roots and grass are generated by the page's
JavaScript from a fixed seed, so first save the page after its scripts have run:

    "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome" --headless=new \
        --virtual-time-budget=3000 --dump-dom "file://$PWD/site/index.html" > Claude/website/dom.html
    python3 tools/export_website_art.py Claude/website/dom.html

Writes (paths relative to the repo root):
    assets/art/world/sky.svg          1152x648, the sky gradient (.sky)
    assets/art/world/sun.svg          the sun with its halo rings and glow (.sun, rebuilt from CSS)
    assets/art/world/cloud.svg        one cloud (#cloudShape)
    assets/art/world/hills_loop.svg   hills + trees, 2880 wide: the page's 1440 plus a mirrored copy
    assets/art/world/ground_loop.svg  ground + rocks, roots, grass, 2880 wide, same mirroring
    assets/art/hollow/eyes.svg        the Hollow's eyes (.eyes), without the CSS animations

The page's left and right edges don't match, so a plain 1440 tile would show a step where it
repeats. Original + mirror meets itself at both joins, so the 2880 tile loops cleanly.

Godot import scales (svg/scale in each .import file), chosen to match the website's layout at a
648 px tall screen:
    sky 1.0, sun 0.8, cloud 1.0, hills_loop 0.8, ground_loop 0.8, eyes 1.0
"""

import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SVG_NS = 'xmlns="http://www.w3.org/2000/svg"'


def balanced(src: str, open_pattern: str, tag: str) -> str:
    """Returns the element starting at open_pattern, through its matching closing tag."""
    start = re.search(open_pattern, src)
    if not start:
        sys.exit(f"export_website_art: '{open_pattern}' not found; was the page saved after its scripts ran?")
    depth, pos = 0, start.start()
    for m in re.finditer(rf"<(/?){tag}\b[^>]*?(/?)>", src[pos:]):
        if m.group(1):
            depth -= 1
        elif not m.group(2):
            depth += 1
        if depth == 0:
            return src[pos:pos + m.end()]
    sys.exit(f"export_website_art: no closing </{tag}> for '{open_pattern}'.")


def inner(element: str) -> str:
    return element[element.index(">") + 1:element.rindex("<")]


def strip_attrs(markup: str, names: tuple[str, ...]) -> str:
    for name in names:
        markup = re.sub(rf'\s{name}="[^"]*"', "", markup)
    return markup


def loop_svg(content: str, view_y: float, width: float, height: float) -> str:
    # Duplicate ids would clash between the two copies, and nothing here references them.
    content = strip_attrs(content, ("id", "class"))
    return (f'<svg {SVG_NS} width="{2 * width:g}" height="{height:g}" '
            f'viewBox="0 {view_y:g} {2 * width:g} {height:g}">'
            f'<g>{content}</g>'
            f'<g transform="translate({2 * width:g} 0) scale(-1 1)">{content}</g></svg>\n')


def sky_svg() -> str:
    return (f'<svg {SVG_NS} width="1152" height="648" viewBox="0 0 1152 648">'
            '<defs><linearGradient id="sky" x1="0" y1="0" x2="0" y2="1">'
            '<stop offset="0" stop-color="#C4E1F2"/><stop offset=".42" stop-color="#DCEEF7"/>'
            '<stop offset=".78" stop-color="#F4F4EA"/><stop offset="1" stop-color="#FCEFD9"/>'
            '</linearGradient></defs><rect width="1152" height="648" fill="url(#sky)"/></svg>\n')


def sun_svg() -> str:
    # .sun at its largest: 104 px wide, halo rings 18 and 40 px wide, glow 0 0 80px 24px.
    r = 52
    glow = r + 24 + 80
    return (f'<svg {SVG_NS} width="{2 * glow}" height="{2 * glow}" viewBox="{-glow} {-glow} {2 * glow} {2 * glow}">'
            '<defs>'
            '<radialGradient id="glow"><stop offset="0" stop-color="#FFC450" stop-opacity=".28"/>'
            f'<stop offset="{(r + 24) / glow:.3f}" stop-color="#FFC450" stop-opacity=".28"/>'
            '<stop offset="1" stop-color="#FFC450" stop-opacity="0"/></radialGradient>'
            '<radialGradient id="disc" cx=".42" cy=".38" r=".62" fx=".42" fy=".38">'
            '<stop offset="0" stop-color="#FFF6CC"/><stop offset=".46" stop-color="#FFDE73"/>'
            '<stop offset="1" stop-color="#FFC544"/></radialGradient>'
            '</defs>'
            f'<circle r="{glow}" fill="url(#glow)"/>'
            f'<circle r="{r + 40}" fill="#FFD666" fill-opacity=".12"/>'
            f'<circle r="{r + 18}" fill="#FFD666" fill-opacity=".24"/>'
            f'<circle r="{r}" fill="url(#disc)"/></svg>\n')


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit("usage: export_website_art.py <page saved after its scripts ran>")
    page = Path(sys.argv[1]).read_text(encoding="utf-8")

    hills_match = re.search(r'<div class="hills"[^>]*>\s*(<svg\b.*?</svg>)', page, re.S)
    if not hills_match:
        sys.exit("export_website_art: the hills <svg> wasn't found in the page.")
    hills = inner(hills_match.group(1))
    ground = inner(balanced(page, r'<g id="groundArt">', "g"))
    cloud = inner(balanced(page, r'<symbol id="cloudShape"', "symbol"))
    eyes = balanced(page, r'<svg class="eyes"', "svg")

    # The page also fades the ground out over its lower 40% (.ground mask-image). That's left out:
    # Godot 4.7's SVG importer draws anything inside a <mask> as fully transparent (luminance and
    # alpha masks both), so in the game the ground runs solid to the bottom edge instead.

    eyes_svg = strip_attrs(eyes, ("class", "aria-hidden")).replace("<svg ", f'<svg {SVG_NS} width="300" height="130" ', 1)

    out = {
        "assets/art/world/sky.svg": sky_svg(),
        "assets/art/world/sun.svg": sun_svg(),
        "assets/art/world/cloud.svg": f'<svg {SVG_NS} width="220" height="90" viewBox="0 0 220 90">{cloud}</svg>\n',
        "assets/art/world/hills_loop.svg": loop_svg(hills, 0, 1440, 320),
        "assets/art/world/ground_loop.svg": loop_svg(ground, -50, 1440, 450),
        "assets/art/hollow/eyes.svg": eyes_svg + "\n",
    }
    for rel, svg in out.items():
        svg = re.sub(r">\s+<", "><", svg)
        ET.fromstring(svg)  # fail loudly on malformed output rather than at Godot import
        path = ROOT / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(svg, encoding="utf-8")
        print(f"export_website_art: wrote {rel} ({len(svg):,} bytes)")


if __name__ == "__main__":
    main()
